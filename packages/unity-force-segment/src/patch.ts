import { mkdir, readFile, readdir, rename, rm, writeFile } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { CiError } from '../../sdk/src/index.js'
import { csString, type Segment } from './segment.js'

export const MARKER = '// ci-sdk unity-force-segment'
export const FORCED_CLASS_FILE = 'AdjustCiForcedSegment.cs'
export const GENERATED_HEADER = 'Generated by ci-sdk unity-force-segment'
/** Runtime mode: the class name prefix of a country reader outside the Adjust folder. */
export const COUNTRY_CLASS_PREFIX = 'CiSdkSegmentCountry'

const SKIPPED_DIRS = new Set(['Library', 'Temp', 'obj'])

// Whitespace is matched loosely: the vendored sources are formatted by hand.
export const FACADE = /public\s+static\s+void\s+InitSdk\s*\(\s*AdjustConfig\s/
// The platform layers (AdjustAndroid, AdjustiOS) declare the same InitSdk: the facade is class Adjust.
export const FACADE_CLASS = /\bclass\s+Adjust\b/
const INIT_SDK = /public\s+static\s+void\s+InitSdk\s*\(\s*AdjustConfig\s+(\w+)\s*\)\s*\{/
const GET_ATTRIBUTION =
  /public\s+static\s+void\s+GetAttribution\s*\(\s*Action<AdjustAttribution>\s+(\w+)\s*\)\s*\{/
const GET_ATTRIBUTION_TIMEOUT =
  /public\s+static\s+void\s+GetAttributionWithTimeout\s*\(\s*int\s+\w+\s*,\s*Action<AdjustAttribution>\s+(\w+)\s*\)\s*\{/
export const COUNTRY_SOURCE =
  /public\s+static\s+(async\s+)?Task<string>\s+GetIpCountryCodeAsync\s*\(\s*\)\s*\{/
// Static declarations (not call sites such as instance.GetAttributionWithTimeout(...)).
const TIMEOUT_DECLARATION = /\bstatic\b[^;{}()=]*\bGetAttributionWithTimeout\s*\(/g

/**
 * `text` with every comment blanked out (same length, newlines kept), so a commented-out
 * signature never matches and match offsets stay valid in the original text. String and
 * char literals are skipped so a `//` inside one (a URL) is not taken for a comment.
 */
export function maskComments(text: string): string {
  const out = text.split('')
  const blank = (from: number, to: number): void => {
    for (let k = from; k < to; k++) if (out[k] !== '\n' && out[k] !== '\r') out[k] = ' '
  }
  let i = 0
  while (i < text.length) {
    const c = text[i]
    const next = text[i + 1]
    if (c === '/' && next === '/') {
      const end = text.indexOf('\n', i)
      const stop = end === -1 ? text.length : end
      blank(i, stop)
      i = stop
    } else if (c === '/' && next === '*') {
      const end = text.indexOf('*/', i + 2)
      const stop = end === -1 ? text.length : end + 2
      blank(i, stop)
      i = stop
    } else if ((c === '@' && next === '"') || (c === '@' && next === '$' && text[i + 2] === '"')) {
      // Verbatim string (@"..." or @$"..."; $@" reaches here at its @): "" is an escaped
      // quote, no backslash escapes.
      i += next === '"' ? 2 : 3
      while (i < text.length) {
        if (text[i] === '"' && text[i + 1] === '"') i += 2
        else if (text[i] === '"') break
        else i++
      }
      i++
    } else if (c === '"' || c === "'") {
      i++
      while (i < text.length && text[i] !== c && text[i] !== '\n') i += text[i] === '\\' ? 2 : 1
      i++
    } else {
      i++
    }
  }
  return out.join('')
}

export interface SavedFile {
  /** Path relative to `root`, with forward slashes. */
  path: string
  /** Original bytes, base64. */
  original: string
}

/** What `restore` needs to put the project back exactly as it was. */
export interface State {
  version: 1
  root: string
  files: SavedFile[]
  added: string[]
}

export function defaultStateFile(env: NodeJS.ProcessEnv = process.env): string {
  const base = env['RUNNER_TEMP'] || os.tmpdir()
  return path.join(base, 'ci-sdk-unity-force-segment', 'state.json')
}

export async function exists(file: string): Promise<boolean> {
  try {
    await readFile(file)
    return true
  } catch {
    return false
  }
}

/** All `.cs` files under `dir`, skipping Unity's generated and hidden folders. */
export async function listCsFiles(dir: string): Promise<string[]> {
  const found: string[] = []
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      // Unity ignores folders ending in "~" and dot-folders when importing.
      if (SKIPPED_DIRS.has(entry.name) || entry.name.startsWith('.') || entry.name.endsWith('~'))
        continue
      found.push(...(await listCsFiles(full)))
    } else if (entry.isFile() && entry.name.endsWith('.cs')) {
      found.push(full)
    }
  }
  return found.sort()
}

export interface Source {
  file: string
  buffer: Buffer
  /** Decoded as UTF-8 without stripping a BOM, so writing it back keeps the BOM. */
  text: string
}

export async function readSources(assets: string): Promise<Source[]> {
  const sources: Source[] = []
  for (const file of await listCsFiles(assets)) {
    const buffer = await readFile(file)
    sources.push({ file, buffer, text: buffer.toString('utf8') })
  }
  return sources
}

/**
 * Insert `statement` as the first statement of the method body whose `{` ends the
 * `match`, in the file's own line-ending style.
 */
export function insertFirstStatement(
  text: string,
  match: { index: number; 0: string },
  statement: string
): string {
  const eol = text.includes('\r\n') ? '\r\n' : '\n'
  const after = match.index + match[0].length
  const lineStart = text.lastIndexOf('\n', match.index) + 1
  const lead = /^[ \t]*/.exec(text.slice(lineStart))?.[0] ?? ''
  const indent = lead + (lead.includes('\t') ? '\t' : '    ')
  return `${text.slice(0, after)}${eol}${indent}${statement} ${MARKER}${text.slice(after)}`
}

/** Patch the Adjust facade. Throws when the vendored SDK has a layout we do not know. */
export function patchFacade(text: string, file: string): string {
  if (text.includes(MARKER)) {
    throw new CiError('E_PATCH', `${file} is already patched; run mode: restore first`)
  }
  const code = maskComments(text)
  const init = INIT_SDK.exec(code)
  const get = GET_ATTRIBUTION.exec(code)
  if (!init || !get) {
    const missing = [init ? '' : 'InitSdk(AdjustConfig)', get ? '' : 'GetAttribution(Action)']
    throw new CiError(
      'E_PATCH',
      `Adjust SDK layout not supported: ${file} has no ${missing.filter(Boolean).join(' or ')}`
    )
  }
  // Optional in the SDK, but every overload must be patched: one we cannot read would
  // return the real attribution.
  const withTimeout = [...code.matchAll(new RegExp(GET_ATTRIBUTION_TIMEOUT.source, 'g'))]
  if (withTimeout.length !== [...code.matchAll(TIMEOUT_DECLARATION)].length) {
    throw new CiError(
      'E_PATCH',
      `Adjust SDK layout not supported: ${file} declares GetAttributionWithTimeout in an unknown form`
    )
  }

  // Edit from the end so earlier match offsets stay valid.
  const edits: [RegExpMatchArray & { index: number }, string][] = [
    [
      init,
      // Guarded: the SDK's own null check (log and return) comes after this line.
      `if (${init[1]} != null) { ${init[1]}.AttributionChangedDelegate = AdjustCiForcedSegment.Wrap(${init[1]}.AttributionChangedDelegate); }`
    ],
    [get, `${get[1]} = AdjustCiForcedSegment.Wrap(${get[1]});`]
  ]
  for (const m of withTimeout) {
    edits.push([m, `${m[1]} = AdjustCiForcedSegment.Wrap(${m[1]});`])
  }
  edits.sort((a, b) => b[0].index - a[0].index)
  let result = text
  for (const [match, statement] of edits) result = insertFirstStatement(result, match, statement)
  return result
}

/** Make `GetIpCountryCodeAsync` answer a fixed country. */
export function patchCountrySource(
  text: string,
  file: string,
  country: string,
  /** The text already carries this run's facade patch (same file). */
  facadePatched = false
): string {
  if (!facadePatched && text.includes(MARKER)) {
    throw new CiError('E_PATCH', `${file} is already patched; run mode: restore first`)
  }
  const match = COUNTRY_SOURCE.exec(maskComments(text))
  if (!match) throw new CiError('E_PATCH', `${file}: GetIpCountryCodeAsync not found`)
  const statement = match[1]
    ? `return "${country}";`
    : `return System.Threading.Tasks.Task.FromResult("${country}");`
  return insertFirstStatement(text, match, statement)
}

/** Source of the C# class that replaces every attribution. */
export function forcedSegmentSource(segment: Segment): string {
  const c = csString
  return `// ${GENERATED_HEADER}. CI build only, never commit.
using System;
using UnityEngine;

namespace AdjustSdk
{
    internal static class AdjustCiForcedSegment
    {
        private const string ForcedTrackerName = "${c(segment.trackerName)}";
        private const string ForcedNetwork = "${c(segment.network)}";
        private const string ForcedCampaign = "${c(segment.campaign)}";
        private const string ForcedAdgroup = "${c(segment.adgroup)}";
        private const string ForcedCreative = "${c(segment.creative)}";

        public static Action<AdjustAttribution> Wrap(Action<AdjustAttribution> callback)
        {
            if (callback == null)
            {
                return null;
            }
            return real => callback(Force(real));
        }

        // Also forces when Adjust answered nothing, so the segment does not depend on the network.
        public static AdjustAttribution Force(AdjustAttribution real)
        {
            Debug.Log("[ci-sdk] forced Adjust attribution: network=" + ForcedNetwork + " campaign=" + ForcedCampaign);
            return new AdjustAttribution
            {
                TrackerToken = real?.TrackerToken ?? "",
                TrackerName = ForcedTrackerName,
                Network = ForcedNetwork,
                Campaign = ForcedCampaign,
                Adgroup = ForcedAdgroup,
                Creative = ForcedCreative,
                ClickLabel = ""
            };
        }
    }
}
`
}

export interface ApplyOptions {
  projectRoot: string
  segment: Segment
  stateFile: string
}

export const rel = (root: string, file: string): string =>
  path.relative(root, file).split(path.sep).join('/')

/**
 * Patch the project. Every new content is computed first (so a layout error changes
 * nothing), then the state is written, then the files.
 * @returns project-relative paths of the files changed or added.
 */
export async function applyPatch(options: ApplyOptions): Promise<string[]> {
  const { segment, stateFile } = options
  const root = path.resolve(options.projectRoot)
  const assets = path.join(root, 'Assets')
  if (!(await isDir(assets))) throw new CiError('E_PATCH', `No Assets folder in ${root}`)

  // A state left by a job that never restored (self-hosted runner) must not become
  // the "original" of this run.
  if (await exists(stateFile)) await restorePatch(stateFile)

  const sources = await readSources(assets)

  const masked = new Map(sources.map(s => [s.file, maskComments(s.text)]))
  const code = (s: Source): string => masked.get(s.file) ?? ''
  const facades = sources.filter(s => FACADE.test(code(s)) && FACADE_CLASS.test(code(s)))
  if (facades.length === 0) {
    throw new CiError(
      'E_PATCH',
      'Adjust SDK not found: no .cs file under Assets declares InitSdk(AdjustConfig)'
    )
  }
  if (facades.length > 1) {
    const list = facades.map(s => rel(root, s.file)).join(', ')
    throw new CiError('E_PATCH', `Several Adjust facades found (${list}); cannot choose one`)
  }
  const facade = facades[0]!

  const changes = new Map<string, { source: Source; text: string }>()
  changes.set(facade.file, {
    source: facade,
    text: patchFacade(facade.text, rel(root, facade.file))
  })

  if (segment.country !== undefined) {
    const country = segment.country
    const owners = sources.filter(s => COUNTRY_SOURCE.test(code(s)))
    if (owners.length === 0) {
      throw new CiError(
        'E_PATCH',
        'country is set but no known IP country source (GetIpCountryCodeAsync) was found'
      )
    }
    for (const owner of owners) {
      // The facade file itself may hold the country source: patch on top of its edits.
      const earlier = changes.get(owner.file)
      changes.set(owner.file, {
        source: owner,
        text: patchCountrySource(
          earlier?.text ?? owner.text,
          rel(root, owner.file),
          country,
          !!earlier
        )
      })
    }
  }

  const classFile = path.join(path.dirname(facade.file), FORCED_CLASS_FILE)
  const stale = sources.find(s => s.file === classFile)
  const added: string[] = []
  const files: SavedFile[] = [...changes.values()].map(({ source }) => ({
    path: rel(root, source.file),
    original: source.buffer.toString('base64')
  }))
  // A leftover of ours is just deleted on restore; anything else is restored byte-exact.
  if (!stale) added.push(rel(root, classFile))
  else if (stale.text.includes(GENERATED_HEADER)) added.push(rel(root, classFile))
  else files.push({ path: rel(root, classFile), original: stale.buffer.toString('base64') })

  const state: State = { version: 1, root, files, added }
  await mkdir(path.dirname(stateFile), { recursive: true })
  // Write then rename: a job killed mid-write never leaves a truncated state behind.
  await writeFile(`${stateFile}.tmp`, JSON.stringify(state, null, 2))
  await rename(`${stateFile}.tmp`, stateFile)

  for (const { source, text } of changes.values()) await writeFile(source.file, text, 'utf8')
  await writeFile(classFile, forcedSegmentSource(segment), 'utf8')

  return [...changes.values()].map(c => rel(root, c.source.file)).concat(rel(root, classFile))
}

export async function isDir(dir: string): Promise<boolean> {
  try {
    await readdir(dir)
    return true
  } catch {
    return false
  }
}

/**
 * Put every file back and drop the added ones (and their Unity `.meta`).
 * Safe after a half-done apply: untouched files are simply rewritten with their own bytes.
 * @returns false when there was no state (nothing to restore).
 */
export async function restorePatch(stateFile: string): Promise<boolean> {
  let raw: string
  try {
    raw = await readFile(stateFile, 'utf8')
  } catch {
    return false
  }
  let state: State
  try {
    state = JSON.parse(raw) as State
  } catch {
    // Unreadable (never written by the atomic rename above): it cannot be restored, and
    // keeping it would block every later apply. Tracked files are reset by the checkout.
    await rm(stateFile, { force: true })
    return false
  }
  // The project is gone (another checkout path): nothing to put back.
  if (!(await isDir(state.root))) {
    await rm(stateFile, { force: true })
    return false
  }
  for (const saved of state.files) {
    await writeFile(path.join(state.root, saved.path), Buffer.from(saved.original, 'base64'))
  }
  for (const added of state.added) {
    const file = path.join(state.root, added)
    await rm(file, { force: true })
    await rm(`${file}.meta`, { force: true })
  }
  await rm(stateFile, { force: true })
  return true
}

/**
 * Delete a generated class (and its `.meta`) left under `Assets` by a job that was killed
 * mid-build. Used when there is no state, e.g. in a fresh RUNNER_TEMP. Tracked files need
 * nothing: `actions/checkout` resets them.
 * @returns project-relative paths removed.
 */
export async function removeStaleGenerated(projectRoot: string): Promise<string[]> {
  const root = path.resolve(projectRoot)
  const assets = path.join(root, 'Assets')
  if (!(await isDir(assets))) return []
  const removed: string[] = []
  for (const file of await listCsFiles(assets)) {
    const base = path.basename(file)
    // The facade class, or a country reader of the runtime mode (runtime.ts).
    if (base !== FORCED_CLASS_FILE && !base.startsWith(COUNTRY_CLASS_PREFIX)) continue
    // Only our own output: a user file that happens to share the name stays.
    if (!(await readFile(file, 'utf8')).includes(GENERATED_HEADER)) continue
    await rm(file, { force: true })
    await rm(`${file}.meta`, { force: true })
    removed.push(rel(root, file))
  }
  return removed
}
