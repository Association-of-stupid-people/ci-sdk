import { mkdir, readFile, readdir, rename, rm, stat, writeFile } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { CiError } from '../../sdk/src/index.js'
import {
  ASMDEF_FILE,
  GENERATED_DIR,
  GENERATED_HEADER,
  SCRIPT_FILE,
  asmdefSource,
  buildScriptSource,
  type BuildScriptOptions
} from './script.js'

/** Unity rewrites it when the build script changes PlayerSettings: saved and put back byte-exact. */
export const PROJECT_SETTINGS = 'ProjectSettings/ProjectSettings.asset'

interface SavedFile {
  /** Relative to `root`, forward slashes. */
  path: string
  /** Original bytes, base64. */
  original: string
}

/** What `restore` needs to put the project back and clean up. */
export interface State {
  version: 1
  root: string
  files: SavedFile[]
  /** Project-relative files or folders added (each with its Unity `.meta`). */
  added: string[]
  /** Keystore written from base64, deleted on restore. */
  keystore: string | undefined
}

export function workDir(env: NodeJS.ProcessEnv = process.env): string {
  return path.join(env['RUNNER_TEMP'] || os.tmpdir(), 'ci-sdk-unity-android-build-script')
}

export const stateFileIn = (dir: string): string => path.join(dir, 'state.json')
export const keysDirIn = (dir: string): string => path.join(dir, 'keys')

async function exists(target: string): Promise<boolean> {
  try {
    await stat(target)
    return true
  } catch {
    return false
  }
}

/** True when `Assets/CiSdkBuild` holds our generated script (a leftover of a killed job). */
async function generatedDirIsOurs(root: string): Promise<boolean> {
  try {
    const text = await readFile(path.join(root, GENERATED_DIR, SCRIPT_FILE), 'utf8')
    return text.includes(GENERATED_HEADER)
  } catch {
    return false
  }
}

async function removeWithMeta(target: string): Promise<void> {
  await rm(target, { recursive: true, force: true })
  await rm(`${target}.meta`, { force: true })
}

export interface ApplyOptions {
  projectRoot: string
  stateFile: string
  script: BuildScriptOptions
  /** A keystore written from base64: recorded so restore deletes it. */
  writtenKeystore: string | undefined
}

/**
 * Add the generated build script. The project settings are saved first (Unity rewrites them during
 * the build), then the state is written, then the files.
 * @returns project-relative paths added or saved.
 */
export async function applyPatch(options: ApplyOptions): Promise<string[]> {
  const root = path.resolve(options.projectRoot)
  if (!(await exists(path.join(root, 'Assets')))) {
    throw new CiError('E_PATCH', `No Assets folder in ${root}`)
  }
  const settingsFile = path.join(root, PROJECT_SETTINGS)
  let settings: Buffer
  try {
    settings = await readFile(settingsFile)
  } catch {
    throw new CiError('E_PATCH', `${PROJECT_SETTINGS} not found in ${root}`)
  }

  const dir = path.join(root, GENERATED_DIR)
  if (await exists(dir)) {
    if (!(await generatedDirIsOurs(root))) {
      throw new CiError(
        'E_PATCH',
        `${GENERATED_DIR} exists and was not generated by ci-sdk: refusing to overwrite it`
      )
    }
    await removeWithMeta(dir)
  }

  const state: State = {
    version: 1,
    root,
    files: [{ path: PROJECT_SETTINGS, original: settings.toString('base64') }],
    added: [GENERATED_DIR],
    keystore: options.writtenKeystore
  }
  await mkdir(path.dirname(options.stateFile), { recursive: true })
  // Write then rename: a job killed mid-write never leaves a truncated state.
  await writeFile(`${options.stateFile}.tmp`, JSON.stringify(state, null, 2))
  await rename(`${options.stateFile}.tmp`, options.stateFile)

  await mkdir(dir, { recursive: true })
  await writeFile(path.join(dir, SCRIPT_FILE), buildScriptSource(options.script), 'utf8')
  await writeFile(path.join(dir, ASMDEF_FILE), asmdefSource(), 'utf8')
  return [`${GENERATED_DIR}/${SCRIPT_FILE}`, `${GENERATED_DIR}/${ASMDEF_FILE}`, PROJECT_SETTINGS]
}

/**
 * Put the saved files back, remove the added ones (with their `.meta`) and the written keystore.
 * @returns false when there was no state.
 */
export async function restorePatch(stateFile: string): Promise<boolean> {
  let raw: string
  try {
    raw = await readFile(stateFile, 'utf8')
  } catch {
    return false
  }
  let state: State
  try {
    state = JSON.parse(raw) as State
  } catch {
    // Never written by the atomic rename above: nothing can be restored from it.
    await rm(stateFile, { force: true })
    return false
  }
  // The project and the keystore are each cleaned even when the other fails; a project error is the
  // one thrown, with a keystore error added to it. The state stays until both are done, so the next
  // restore tries again.
  let projectError: Error | undefined
  try {
    if (await exists(state.root)) {
      for (const saved of state.files) {
        await writeFile(path.join(state.root, saved.path), Buffer.from(saved.original, 'base64'))
      }
      for (const added of state.added) await removeWithMeta(path.join(state.root, added))
    }
  } catch (err) {
    projectError = err instanceof Error ? err : new Error(String(err))
  }
  if (state.keystore) {
    try {
      await rm(state.keystore, { force: true, maxRetries: 5, retryDelay: 200 })
    } catch (err) {
      if (!projectError) throw err
      projectError.message += `; the keystore was not deleted either: ${err instanceof Error ? err.message : String(err)}`
    }
  }
  if (projectError) throw projectError
  await rm(stateFile, { force: true })
  return true
}

/**
 * Without a state (a fresh RUNNER_TEMP after a killed job): delete our generated folder, found by
 * its header, and any keystore left in the work dir. Tracked files need nothing: the checkout
 * resets them.
 * @returns what was removed.
 */
export async function removeStale(projectRoot: string, keysDir: string): Promise<string[]> {
  const root = path.resolve(projectRoot)
  const removed: string[] = []
  if (await generatedDirIsOurs(root)) {
    await removeWithMeta(path.join(root, GENERATED_DIR))
    removed.push(GENERATED_DIR)
  }
  let keys: string[] = []
  try {
    keys = await readdir(keysDir)
  } catch {
    // no work dir
  }
  for (const key of keys) {
    await rm(path.join(keysDir, key), { force: true })
    removed.push(`keystore ${key}`)
  }
  return removed
}
