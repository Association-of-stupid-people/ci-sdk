export interface BuildScriptOptions {
  format: 'aab' | 'apk'
  /** Relative to the project, or absolute. */
  output: string
  /** Empty = keep the project's bundleVersion. */
  versionName: string
  /** 0 = keep the project's version code. */
  versionCode: number
  development: boolean
  releaseSigning: boolean
  /**
   * Keystore values baked into the script. A value that came from a secret input is `null`: the
   * script then reads it from the environment (unity-build's keystore-* inputs). The path in the
   * environment always wins (docker mode maps it). The password, alias and alias password come
   * from the environment as a set when any of them is there, else all from the script, so the
   * values of two keystores are never mixed.
   */
  keystore: {
    path: string | null
    password: string | null
    alias: string | null
    aliasPassword: string | null
  }
}

// C0/C1 controls and the Unicode line separators cannot go in a C# regular string literal.
function hasControl(value: string): boolean {
  for (const ch of value) {
    const c = ch.codePointAt(0)!
    if (c <= 0x1f || (c >= 0x7f && c <= 0x9f) || c === 0x2028 || c === 0x2029) return true
  }
  return false
}

/** A C# string literal (or `null`). */
export function csLiteral(value: string | null): string {
  if (value === null) return 'null'
  if (hasControl(value)) throw new Error('control characters cannot go in a C# string')
  return `"${value.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`
}

